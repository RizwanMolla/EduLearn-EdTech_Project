const motifs = ['arcs', 'grid', 'stripes', 'orbit', 'blocks', 'wave', 'stairs'];

const lessonType = (title) => {
  const match = /^(Project|Reading|Quiz):\s*/i.exec(title);
  if (!match) return { type: 'video', title };
  return { type: match[1].toLowerCase(), title: title.slice(match[0].length) };
};

const durationFor = (type, rand) => {
  if (type === 'project') return 40 + Math.round(rand() * 35);
  if (type === 'reading') return 8 + Math.round(rand() * 8);
  if (type === 'quiz') return 10;
  return 7 + Math.round(rand() * 13);
};

const normalize = (course, index) => {
  const rand = seeded(course.slug);
  const sections = course.curriculum.map((section, s) => {
    const items = [...section.lessons];
    if (s === course.curriculum.length - 1) items.push('Quiz: Knowledge check');
    const lessons = items.map((raw, l) => {
      const { type, title } = lessonType(raw);
      return {
        id: `${s}-${l}`,
        title,
        type,
        duration: durationFor(type, rand),
        preview: s === 0 && l < 2,
      };
    });
    return {
      title: section.title,
      lessons,
      duration: lessons.reduce((sum, l) => sum + l.duration, 0),
    };
  });

  const lessons = sections.flatMap((section) => section.lessons);
  return {
    ...course,
    motif: motifs[index % motifs.length],
    number: String(course.id).padStart(2, '0'),
    curriculum: sections,
    lessons,
    lessonCount: lessons.length,
    totalMinutes: lessons.reduce((sum, l) => sum + l.duration, 0),
    projectCount: lessons.filter((l) => l.type === 'project').length,
  };
};

export const courses = rawCourses.map(normalize);

export const getCourse = (idOrSlug) => {
  if (idOrSlug === undefined || idOrSlug === null) return undefined;
  const key = String(idOrSlug);
  return courses.find((c) => String(c.id) === key || c.slug === key);
};

export const coursesByInstructor = (instructorId) => courses.filter((c) => c.instructor === instructorId);

export const coursesByCategory = (categoryId) => courses.filter((c) => c.category === categoryId);

export const relatedCourses = (course, count = 3) => {
  const same = courses.filter((c) => c.category === course.category && c.id !== course.id);
  const rest = courses
    .filter((c) => c.category !== course.category && c.id !== course.id)
    .sort((a, b) => b.students - a.students);
  return [...same, ...rest].slice(0, count);
};

export const featuredCourses = () => [...courses].sort((a, b) => b.students - a.students).slice(0, 6);

export const discountPercent = (course) =>
  course.originalPrice ? Math.round((1 - course.price / course.originalPrice) * 100) : 0;
